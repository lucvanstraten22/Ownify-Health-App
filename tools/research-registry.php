<?php
/**
 * The research registry: config/research.php (the reviewed text) and the
 * database tables the insight engine reads (research_sources,
 * research_claims — migration 028), kept the same. docs/RESEARCH.md.
 *
 *     php tools/research-registry.php --check   change nothing; exit 1 when
 *                                               anything below disagrees
 *     php tools/research-registry.php --sql     print the registry seed
 *     php tools/research-registry.php --write   put that seed into migrations 028,
 *                                               029 and database/schema.sql
 *     php tools/research-registry.php --sync    write config/research.php into
 *                                               the database (DB_NAME …), in
 *                                               one transaction
 *
 * --check looks at:
 *   - config/research.php itself: every claim names an approved source,
 *     every hosted PDF is CC BY and there (research_config_problems());
 *   - the English: every Dutch sentence a person reads has an entry in
 *     lang/en/ (the kinds, strengths, findings, claims, populations and
 *     limitations);
 *   - migrations 028 and 029 and schema.sql: their seed is exactly what --sql prints;
 *   - the database, when one is reachable and has the tables: every source
 *     and every claim version as reviewed, nothing active that is not.
 *
 * --sync never deletes. A source that left the file is marked withdrawn, a
 * claim that left it (or got a newer version) retired, so insights stored
 * with it keep pointing at what they used. A claim whose content changed
 * without a higher `version` is refused: a new meaning is a new version.
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
require_once $root . '/includes/research.php';

$mode = $argv[1] ?? '--check';
if (!in_array($mode, ['--check', '--sql', '--write', '--sync'], true)) {
    fwrite(STDERR, "Usage: php tools/research-registry.php --check | --sql | --write | --sync\n");
    exit(2);
}

$config  = research_config();
$sources = (array) $config['sources'];
$claims  = (array) $config['claims'];

const SEED_BEGIN = '-- >>> REGISTRY SEED: generated by php tools/research-registry.php --write. Do not edit by hand.';
const SEED_END   = '-- <<< REGISTRY SEED';

/* ------------------------------------------------------------- the seed */

/**
 * A value as an SQL literal that reads the same in every sql_mode:
 * quotes doubled, and no backslash anywhere (refused, not escaped).
 */
function registry_literal(mixed $value): string
{
    if ($value === null) {
        return 'NULL';
    }
    if (is_int($value)) {
        return (string) $value;
    }
    $text = (string) $value;
    if (str_contains($text, '\\')) {
        fwrite(STDERR, "A registry value contains a backslash, which an SQL literal cannot hold the same way in every sql_mode:\n  $text\n");
        exit(1);
    }

    return "'" . str_replace("'", "''", $text) . "'";
}

/** INSERT IGNORE for the reviewed rows: never overwrites what is there. */
function registry_seed(array $sources, array $claims): string
{
    $sourceRows = [];
    foreach ($sources as $code => $source) {
        $sourceRows[] = research_source_row((string) $code, $source);
    }
    $claimRows = [];
    foreach ($claims as $key => $claim) {
        $claimRows[] = research_claim_row((string) $key, $claim, $sources);
    }

    $insert = static function (string $table, array $rows): string {
        $columns = array_keys($rows[0]);
        $lines   = [];
        foreach ($rows as $row) {
            $lines[] = '    (' . implode(', ', array_map('registry_literal', array_values($row))) . ')';
        }

        return 'INSERT IGNORE INTO `' . $table . '` (`' . implode('`, `', $columns) . "`) VALUES\n"
            . implode(",\n", $lines) . ";\n";
    };

    return SEED_BEGIN . "\n"
        . '-- ' . count($sourceRows) . ' approved sources and ' . count($claimRows) . " claims (config/research.php).\n"
        . $insert('research_sources', $sourceRows)
        . "\n"
        . $insert('research_claims', $claimRows)
        . SEED_END . "\n";
}

$seed  = registry_seed($sources, $claims);
/* The two files that carry the seed: the migration and the fresh install. */
$files = [
    'database/migrations/028-research-insights.sql' => $root . '/database/migrations/028-research-insights.sql',
    'database/migrations/029-correlations.sql'      => $root . '/database/migrations/029-correlations.sql',
    'database/schema.sql'                           => $root . '/database/schema.sql',
];

if ($mode === '--sql') {
    echo $seed;
    exit(0);
}

if ($mode === '--write') {
    foreach ($files as $name => $file) {
        $sql  = (string) @file_get_contents($file);
        $from = strpos($sql, SEED_BEGIN);
        $to   = strpos($sql, SEED_END);
        if ($from === false || $to === false || $to < $from) {
            fwrite(STDERR, "$name has no seed markers\n");
            exit(1);
        }
        $sql = substr($sql, 0, $from) . $seed . substr($sql, $to + strlen(SEED_END) + 1);
        file_put_contents($file, $sql);
        echo "Wrote the seed into $name\n";
    }
    exit(0);
}

/* ------------------------------------------------------------ the sync */

/** The database the app is configured for, or null. */
function registry_pdo(): ?PDO
{
    $pdo = db();
    if ($pdo === null) {
        return null;
    }

    return research_installed() ? $pdo : null;
}

if ($mode === '--sync') {
    $problems = research_config_problems($config);
    if ($problems !== []) {
        fwrite(STDERR, "config/research.php is not ready:\n  - " . implode("\n  - ", $problems) . "\n");
        exit(1);
    }

    $pdo = registry_pdo();
    if ($pdo === null) {
        fwrite(STDERR, "No database with the registry tables (import migration 028 first). " . (db_note_failure() ?? '') . "\n");
        exit(1);
    }

    $changes = [];
    try {
        $pdo->beginTransaction();

        foreach ($sources as $code => $source) {
            $row  = research_source_row((string) $code, $source);
            $have = db_one('SELECT content_hash, status FROM research_sources WHERE code = ? FOR UPDATE', [$code]);
            if ($have === null) {
                db_run('INSERT INTO research_sources (`' . implode('`, `', array_keys($row)) . '`) VALUES ('
                    . implode(', ', array_fill(0, count($row), '?')) . ')', array_values($row));
                $changes[] = "source $code added";
            } elseif ($have['content_hash'] !== $row['content_hash'] || $have['status'] !== $row['status']) {
                $sets = implode(', ', array_map(static fn ($c) => "`$c` = ?", array_keys($row)));
                db_run("UPDATE research_sources SET $sets, synced_at = NOW() WHERE code = ?", [...array_values($row), $code]);
                $changes[] = "source $code updated";
            }
        }
        foreach (db_all("SELECT code FROM research_sources WHERE status = 'approved'") as $have) {
            if (!isset($sources[$have['code']])) {
                db_run("UPDATE research_sources SET status = 'withdrawn', synced_at = NOW() WHERE code = ?", [$have['code']]);
                $changes[] = 'source ' . $have['code'] . ' withdrawn (no longer in the file)';
            }
        }

        foreach ($claims as $key => $claim) {
            $row  = research_claim_row((string) $key, $claim, $sources);
            $have = db_one('SELECT id, content_hash, status FROM research_claims WHERE claim_key = ? AND version = ? FOR UPDATE',
                [$key, $row['version']]);
            if ($have === null) {
                db_run('INSERT INTO research_claims (`' . implode('`, `', array_keys($row)) . '`) VALUES ('
                    . implode(', ', array_fill(0, count($row), '?')) . ')', array_values($row));
                $changes[] = "claim $key v{$row['version']} added";
            } elseif ($have['content_hash'] !== $row['content_hash']) {
                throw new RuntimeException("claim $key v{$row['version']} changed without a new version: raise `version` in config/research.php");
            } elseif ($have['status'] !== 'active') {
                db_run("UPDATE research_claims SET status = 'active', retired_at = NULL WHERE id = ?", [$have['id']]);
                $changes[] = "claim $key v{$row['version']} active again";
            }
            $retired = db_run("UPDATE research_claims SET status = 'retired', retired_at = NOW()
                                WHERE claim_key = ? AND version <> ? AND status = 'active'", [$key, $row['version']]);
            if ($retired !== null && $retired->rowCount() > 0) {
                $changes[] = "claim $key: older version retired";
            }
        }
        foreach (db_all("SELECT id, claim_key, version FROM research_claims WHERE status = 'active'") as $have) {
            if (!isset($claims[$have['claim_key']])) {
                db_run("UPDATE research_claims SET status = 'retired', retired_at = NOW() WHERE id = ?", [$have['id']]);
                $changes[] = 'claim ' . $have['claim_key'] . ' v' . $have['version'] . ' retired (no longer in the file)';
            }
        }

        $pdo->commit();
    } catch (Throwable $e) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        fwrite(STDERR, 'Nothing was written: ' . $e->getMessage() . "\n");
        exit(1);
    }

    echo $changes === [] ? "The database already holds config/research.php.\n" : implode("\n", $changes) . "\n";
    exit(0);
}

/* ----------------------------------------------------------- the check */

$problems = research_config_problems($config);

/* The English for every Dutch sentence a person reads. */
$catalog = (array) require $root . '/lang/en.php';
$dutch   = [];
foreach ($config['kinds'] as $text) {
    $dutch[] = $text;
}
foreach ($config['strengths'] as $strength) {
    $dutch[] = $strength['label'];
    $dutch[] = $strength['means'];
}
$dutch[] = $config['strength_note'];
array_push($dutch, ...array_values((array) $config['applicability']));
array_walk_recursive($config['detail'], static function ($text) use (&$dutch): void {
    $dutch[] = $text;
});
foreach ($sources as $source) {
    $dutch[] = $source['findings'];
}
foreach ($claims as $claim) {
    $dutch[] = $claim['statement'];
    $dutch[] = $claim['population'];
    array_push($dutch, ...array_values((array) $claim['limitations']));
}
foreach (array_unique($dutch) as $text) {
    if (!isset($catalog[$text])) {
        $problems[] = 'no English for: ' . $text;
    }
}

/* Migrations 028 and 029 and schema.sql carry exactly this seed. */
foreach ($files as $name => $file) {
    $sql  = (string) @file_get_contents($file);
    $from = strpos($sql, SEED_BEGIN);
    $to   = strpos($sql, SEED_END);
    if ($from === false || $to === false) {
        $problems[] = "$name has no registry seed";
    } elseif (substr($sql, $from, $to + strlen(SEED_END) + 1 - $from) !== $seed) {
        $problems[] = "the seed in $name is out of date: php tools/research-registry.php --write";
    }
}

/* The database, when there is one with the tables. */
$pdo = registry_pdo();
if ($pdo !== null) {
    /* Every column as reviewed — not only the hash, so text stored garbled
       (an import in the wrong character set) or edited by hand shows too. */
    $same = static function (array $want, array $have): array {
        $off = [];
        foreach ($want as $column => $value) {
            $stored = $have[$column] ?? null;
            if ($value === null ? $stored !== null : (string) $stored !== (string) $value) {
                $off[] = $column;
            }
        }
        return $off;
    };

    $dbSources = [];
    foreach (db_all('SELECT * FROM research_sources') as $row) {
        $dbSources[$row['code']] = $row;
    }
    foreach ($sources as $code => $source) {
        $row = research_source_row((string) $code, $source);
        if (!isset($dbSources[$code])) {
            $problems[] = "database: source $code is missing (php tools/research-registry.php --sync)";
        } elseif (($off = $same($row, $dbSources[$code])) !== []) {
            $problems[] = "database: source $code differs from config/research.php in " . implode(', ', $off) . ' (--sync)';
        }
    }
    foreach ($dbSources as $code => $row) {
        if ($row['status'] === 'approved' && !isset($sources[$code])) {
            $problems[] = "database: source $code is approved there but not in config/research.php";
        }
    }

    $active = [];
    foreach (db_all("SELECT * FROM research_claims WHERE status = 'active'") as $row) {
        $active[$row['claim_key']] = $row;
    }
    foreach ($claims as $key => $claim) {
        $row = research_claim_row((string) $key, $claim, $sources);
        $have = $active[$key] ?? null;
        if ($have === null) {
            $problems[] = "database: claim $key has no active version (--sync)";
        } elseif (($off = $same($row, $have)) !== []) {
            $problems[] = "database: claim $key v{$have['version']} differs from v{$row['version']} in config/research.php in " . implode(', ', $off) . ' (--sync)';
        }
    }
    foreach ($active as $key => $row) {
        if (!isset($claims[$key])) {
            $problems[] = "database: claim $key is active there but not in config/research.php";
        }
    }
    $where = 'the database (' . (string) db_value('SELECT DATABASE()') . ')';
} else {
    $where = 'no database with the registry tables, so only the file, the English and the SQL';
}

if ($problems !== []) {
    echo "Research registry: " . count($problems) . " problem(s), checked $where\n  - " . implode("\n  - ", $problems) . "\n";
    exit(1);
}

echo 'Research registry: ' . count($sources) . ' sources, ' . count($claims) . " claims — the file, the English, migrations 028 and 029, schema.sql and $where agree.\n";
exit(0);
