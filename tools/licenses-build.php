<?php
/**
 * The Android app's third-party packages, for Instellingen › Over de app ›
 * Licenties (docs/LEGAL.md): every artifact the release build ships,
 * with its resolved version, the licence its POM names and its source.
 *
 *     cd OwnifyAndroid
 *     ./gradlew -q :app:dependencies --configuration releaseRuntimeClasspath > /tmp/deps.txt
 *     php ../tools/licenses-build.php /tmp/deps.txt [~/.gradle/caches/modules-2/files-2.1]
 *
 * Writes config/licenses-android.php. Gradle is needed to know what the
 * build resolves, so this runs on a machine that builds the app — never on
 * the web server. Run it again after any change to the app's dependencies.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$report = $argv[1] ?? '';
$cache  = $argv[2] ?? (getenv('HOME') . '/.gradle/caches/modules-2/files-2.1');
if (!is_file($report)) {
    fwrite(STDERR, "Give the dependency report: php tools/licenses-build.php deps.txt [gradle-cache]\n");
    exit(1);
}

/* Every resolved coordinate: "g:a:v", "g:a:v -> w" and "g:a -> w" (a BOM's) all resolve to the last version. */
$artifacts = [];
foreach (file($report, FILE_IGNORE_NEW_LINES) as $line) {
    if (!preg_match('/[-+\\\\]--- ([A-Za-z0-9._-]+):([A-Za-z0-9._-]+)(?::([^\s]+))?(?: -> ([^\s]+))?/', $line, $m)) {
        continue;
    }
    $version = ($m[4] ?? '') !== '' ? $m[4] : ($m[3] ?? '');
    if ($version === '' || str_contains($m[1], 'compose-bom') || $m[2] === 'compose-bom') {
        continue;
    }
    $artifacts[$m[1] . ':' . $m[2]] = ['group' => $m[1], 'name' => $m[2], 'version' => $version];
}
ksort($artifacts);

/** The licence names and URL a POM gives — its parent's, when it has none of its own. */
function pom_facts(string $cache, string $group, string $name, string $version, int $depth = 0): array
{
    $poms = glob($cache . '/' . $group . '/' . $name . '/' . $version . '/*/*.pom') ?: [];
    if ($poms === [] || $depth > 3) {
        return ['licences' => [], 'url' => null];
    }
    $xml  = (string) file_get_contents($poms[0]);
    $own  = preg_replace('/<parent>.*?<\/parent>/s', '', $xml);
    preg_match_all('/<license>.*?<name>(.*?)<\/name>/s', $own, $names);
    $body = preg_replace('/<licenses>.*?<\/licenses>|<developers>.*?<\/developers>|<organization>.*?<\/organization>/s', '', $own);
    $url  = preg_match('/<url>(.*?)<\/url>/s', $body, $u) ? trim($u[1]) : null;
    $facts = ['licences' => array_map('trim', $names[1]), 'url' => $url];

    if ($facts['licences'] === [] && preg_match('/<parent>.*?<groupId>(.*?)<\/groupId>.*?<artifactId>(.*?)<\/artifactId>.*?<version>(.*?)<\/version>/s', $xml, $p)) {
        $parent = pom_facts($cache, trim($p[1]), trim($p[2]), trim($p[3]), $depth + 1);
        $facts['licences'] = $parent['licences'];
        $facts['url'] ??= $parent['url'];
    }

    return $facts;
}

/** A POM's licence name as one SPDX identifier, or the name itself. */
function spdx(array $names): string
{
    $name = strtolower(implode(' ', $names));

    return match (true) {
        str_contains($name, 'apache')                         => 'Apache-2.0',
        str_contains($name, 'mit')                            => 'MIT',
        str_contains($name, 'bsd-3') || str_contains($name, 'bsd 3') => 'BSD-3-Clause',
        str_contains($name, 'android software development kit') => 'Android-SDK-License',
        default                                               => implode('; ', $names) ?: 'unknown',
    };
}

$out = [];
foreach ($artifacts as $artifact) {
    $facts = pom_facts($cache, $artifact['group'], $artifact['name'], $artifact['version']);
    $out[] = $artifact + ['licence' => spdx($facts['licences']), 'url' => $facts['url']];
}

$unknown = array_filter($out, static fn ($a) => $a['licence'] === 'unknown');
if ($unknown !== []) {
    fwrite(STDERR, "No licence found for:\n  " . implode("\n  ", array_map(static fn ($a) => $a['group'] . ':' . $a['name'], $unknown)) . "\n");
}

$php = "<?php\n/**\n * Generated by tools/licenses-build.php from the Android release build's\n"
     . " * dependency report (releaseRuntimeClasspath) and the packages' POM files.\n"
     . " * Do not edit by hand: run the tool again after a dependency changes.\n */\n"
     . "declare(strict_types=1);\n\nreturn " . var_export($out, true) . ";\n";
file_put_contents(dirname(__DIR__) . '/config/licenses-android.php', $php);

echo count($out) . " artifacts written to config/licenses-android.php\n";
